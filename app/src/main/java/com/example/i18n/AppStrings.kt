fun stringsForLanguage(language: AppLanguage): AppStrings = when (language) {
    AppLanguage.ENGLISH -> EnglishStrings
    AppLanguage.HINDI -> HindiStrings
    AppLanguage.HINGLISH -> HinglishStrings
    AppLanguage.SPANISH -> SpanishStrings
}

val LocalAppStrings = staticCompositionLocalOf { EnglishStrings }

@Composable
fun ProvideAppStrings(language: AppLanguage, content: @Composable () -> Unit) {
    CompositionLocalProvider(LocalAppStrings provides stringsForLanguage(language)) {
        content()
    }
}
